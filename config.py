"""Shared settings for the GSC SOP RAG assistant."""
import os
from pathlib import Path

from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parent
load_dotenv(ROOT / ".env")

GEMINI_API_KEY = os.getenv("GEMINI_API_KEY", "")
EMBED_MODEL = os.getenv("EMBED_MODEL", "gemini-embedding-001")
# Free tier limits seen in AI Studio (2026-10-13): 3.8 Flash = 5 RPM / 20 requests per DAY,
# 3.5 Flash-Lite = 15 RPM / 500 per day. Every answer needs 1-2 generation calls, so the
# Flash-Lite family is the only practical choice on the free tier (and 8x faster: 2.1 s vs 16.7 s).
GEN_MODEL = os.getenv("GEN_MODEL", "gemini-3.5-flash-lite")

DATA_DIR = ROOT / "data" / "sop"
CHROMA_DIR = ROOT / "chroma_db"
COLLECTION = "gsc_sops"

# Chunking: one chunk per section (## / ###). Sections longer than
# MAX_CHUNK_CHARS are split on paragraph/list boundaries, and the last
# OVERLAP_BLOCKS block(s) of the previous part are repeated at the start
# of the next part so a step is never cut off from its context.
MAX_CHUNK_CHARS = 2500
OVERLAP_BLOCKS = 1

# Retrieval
TOP_K = 5
# Guardrail 1 (cheap, no LLM call): if the best fragment is less similar than
# this, answer "not found in the SOPs" right away. Chosen from eval/test_retrieval.py
# (2026-10-13): weakest in-scope top-1 = 0.663, clearly off-topic questions
# (weather, poem, prompt injection) = 0.50-0.58. Near-domain questions
# (Merchant Center, Google Ads, general SEO: 0.61-0.66) overlap with in-scope
# scores, so they are handled by guardrail 2 - the system prompt rule
# "answer only from the fragments, otherwise say it is not in the SOPs".
RELEVANCE_THRESHOLD = 0.60

# Section expansion ("small-to-big"): fragments are searched as small chunks, but the
# model receives the WHOLE ## section each hit belongs to (steps + reply templates),
# so a reply template stored in a neighbouring chunk is never lost. Max sections in context:
MAX_SECTIONS = 5  # = TOP_K: every retrieved hit keeps its section (was 4 - the full-access
                  # section ranked 5th was dropped for "admin access", test 2026-10-13)

# Generation fallback: if GEN_MODEL is overloaded (HTTP 503) or rate-limited (429)
# after retries, the answer is generated by this model instead.
FALLBACK_MODEL = os.getenv("FALLBACK_MODEL", "gemini-3.1-flash-lite")  # separate quota

# Gemini 3 "thinking" depth: "low" = fast answers for procedure lookups.
# Set THINKING_LEVEL= (empty) in .env to use the model default.
THINKING_LEVEL = os.getenv("THINKING_LEVEL", "low")

# Long sections: above this size only the hit chunks, their neighbours and every chunk
# with a reply template are sent (keeps the context small when SOPs get longer).
MAX_SECTION_CHARS = 6000
